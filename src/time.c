#include "philo.h"

long long	get_time(void)
{
	struct timeval	time;

	gettimeofday(&time, NULL);
	return (time.tv_sec * 1000 + time.tv_usec / 1000);
}

long long	timediff_ms(t_philo *philos)
{
	return (get_time() - philos[0].info->start_time);
}
